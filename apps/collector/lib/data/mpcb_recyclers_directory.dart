  /// Get recyclers matched with live proximity & category filters
  static List<Recycler> getMatchedRecyclers({
    required double collectorLat,
    required double collectorLng,
    String? categoryId,
    String? searchFilter,
    bool sortByPrice = false,
  }) {
    final normCat = _normalizeCategory(categoryId);

    // Compute live distance for each
    final list = allRecyclers.map((r) {
      final liveDist = calculateDistanceKm(
        collectorLat,
        collectorLng,
        r.latitude,
        r.longitude,
      );
      return r.copyWith(distanceKm: liveDist);
    }).where((r) {
      // Category check
      if (normCat.isNotEmpty && normCat != 'all') {
        final matches = r.acceptedCategories.any((cat) =>
            cat == normCat ||
            cat == 'all' ||
            (normCat == 'e_waste' && ['pcb', 'copper_wire', 'display', 'appliances'].contains(cat)) ||
            (normCat == 'copper_wire' && ['non_ferrous', 'copper_wire'].contains(cat)));
        if (!matches) return false;
      }

      // Search text filter
      if (searchFilter != null && searchFilter.trim().isNotEmpty) {
        final q = searchFilter.toLowerCase().trim();
        final text = '${r.name} ${r.address} ${r.contactPerson ?? ''} ${r.categoryLabel ?? ''}'.toLowerCase();
        if (!text.contains(q)) return false;
      }

      return true;
    }).toList();

    // Sort by price (highest first) or distance (nearest first)
    if (sortByPrice) {
      list.sort((a, b) => (b.indicativePrice ?? 0).compareTo(a.indicativePrice ?? 0));
    } else {
      list.sort((a, b) => a.distanceKm.compareTo(b.distanceKm));
    }

    return list;
  }

  static String _normalizeCategory(String? input) {
    if (input == null || input.isEmpty) return 'all';
    final lower = input.toLowerCase().trim();
    if (lower.contains('e_waste') || lower.contains('ewaste') || lower.contains('ई-कचरा')) return 'e_waste';
    if (lower.contains('bat') || lower.contains('बैटरी') || lower.contains('बॅटरी')) return 'battery';
    if (lower.contains('copper') || lower.contains('non_ferrous') || lower.contains('तांबे') || lower.contains('brass')) return 'non_ferrous';
    if (lower.contains('plastic') || lower.contains('प्लॅस्टिक') || lower.contains('प्लास्टिक')) return 'plastic';
    if (lower.contains('ferrous') || lower.contains('iron') || lower.contains('steel') || lower.contains('लोखंड')) return 'ferrous';
    if (lower.contains('vehicle') || lower.contains('गाडी') || lower.contains('scrapping')) return 'vehicle_scrapping';
    if (lower.contains('tyre') || lower.contains('tire') || lower.contains('टायर')) return 'tyre';
    if (lower.contains('oil') || lower.contains('तेल')) return 'used_oil';
    if (lower.contains('solvent') || lower.contains('केमिकल')) return 'spent_solvent';
    return lower;
  }
